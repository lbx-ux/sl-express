def hexagon(lng, lat, radius):
    """正六边形（凸多边形，2dsphere 合法），radius 单位为度"""
    coords = []
    for k in range(6):
        a = k * math.pi / 3
        coords.append([round(lng + radius * math.cos(a), 6),
                       round(lat + radius * math.sin(a), 6)])
    coords.append(coords[0])
    return [coords]

AGENCY_RADIUS = 0.06    # 机构范围：覆盖约 6km 半径（大于县城间距的合理覆盖）
COURIER_RADIUS = 0.025  # 快递员范围：约 2.5km 半径，位于机构范围内

def main():
    docs = []

    # 1. 机构作业范围（type=1）：以县区坐标为中心，机构 bid
    for bid, name, lng, lat in AGENCIES:
        docs.append({
            "bid": bid,
            "type": 1,
            "polygon": {"type": "Polygon", "coordinates": hexagon(lng, lat, AGENCY_RADIUS)},
        })

    # 2. 快递员作业范围（type=2）：以所属机构坐标为中心（半径小于机构，确保落在机构范围内）
    agency_center = {bid: (lng, lat) for bid, name, lng, lat in AGENCIES}
    for bid, name, org_bid in COURIERS:
        org = FALLBACK_ORG.get(org_bid, org_bid)
        if org not in agency_center:
            print(f"⚠️ 快递员 {name}({bid}) 的机构 {org} 无坐标，跳过")
            continue
        lng, lat = agency_center[org]
        docs.append({
            "bid": bid,
            "type": 2,
            "polygon": {"type": "Polygon", "coordinates": hexagon(lng, lat, COURIER_RADIUS)},
        })

    with open("restore_scopes.jsonl", "w") as f:
        for d in docs:
            f.write(json.dumps(d) + "\n")

    t1 = sum(1 for d in docs if d["type"] == 1)
    t2 = sum(1 for d in docs if d["type"] == 2)
    print(f"已生成 {len(docs)} 条（机构 {t1} + 快递员 {t2}）→ restore_scopes.jsonl")
    print("导入：FinalShell 上传到虚拟机 /tmp/ 后执行：")
    print('  docker cp /tmp/restore_scopes.jsonl mongodb:/tmp/restore.jsonl')
    print('  docker exec mongodb mongoimport -u sl -p 123321 --authenticationDatabase admin -d sl_scope -c sl_service_scope --file /tmp/restore.jsonl')
    print('  docker exec mongodb mongo -u sl -p 123321 --authenticationDatabase admin --quiet --eval \'db.getSiblingDB("sl_scope").sl_service_scope.createIndex({polygon:"2dsphere"})\'')

if __name__ == "__main__":
    main()
